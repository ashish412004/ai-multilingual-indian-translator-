"""
Evaluation module using SacreBLEU for standard NLP machine translation metrics.
Computes real BLEU and chrF++ scores.
"""

from typing import List, Dict, Any
import sacrebleu


def compute_metrics(prediction: str, reference: str) -> Dict[str, float]:
    """
    Compute real SacreBLEU metrics:
    - sentence_bleu: Bilingual Evaluation Understudy (0-100)
    - chrF++: Character n-gram F-score with word order 2 (0-100), ideal for morphologically rich Indian languages
    
    Args:
        prediction: Candidate translated string generated by model
        reference: Ground-truth human reference translation
        
    Returns:
        Dictionary containing calculated 'bleu' and 'chrf_plus_plus' scores
    """
    pred_clean = prediction.strip()
    ref_clean = reference.strip()
    
    if not pred_clean or not ref_clean:
        return {"bleu": 0.0, "chrf_plus_plus": 0.0}

    # Standard BLEU score
    bleu_score = sacrebleu.sentence_bleu(pred_clean, [ref_clean]).score
    
    # chrF++ (character n-gram F-score with word n-grams order 2)
    chrf_score = sacrebleu.sentence_chrf(pred_clean, [ref_clean], word_order=2).score
    
    return {
        "bleu": round(bleu_score, 2),
        "chrf_plus_plus": round(chrf_score, 2),
    }


def evaluate_batch(predictions: List[str], references: List[str]) -> Dict[str, Any]:
    """
    Compute corpus-level BLEU and chrF++ across a batch of translation pairs.
    """
    if not predictions or not references or len(predictions) != len(references):
        return {"corpus_bleu": 0.0, "corpus_chrf_plus_plus": 0.0, "pairs_evaluated": 0}

    corpus_bleu = sacrebleu.corpus_bleu(predictions, [references]).score
    corpus_chrf = sacrebleu.corpus_chrf(predictions, [references], word_order=2).score

    return {
        "corpus_bleu": round(corpus_bleu, 2),
        "corpus_chrf_plus_plus": round(corpus_chrf, 2),
        "pairs_evaluated": len(predictions),
    }
